/** How age moves a group (rating points): pace from 30, dribbling from 31, physique before 22 and from 33; passing grows to 32. */
function ageShift(age: number, keeper: boolean): Card {
  const pace = -1.25 * Math.max(0, age - 29) - Math.max(0, age - 32)
  if (keeper) return [0, 0, 0, 0, pace, 0]
  const dribbling = -0.75 * Math.max(0, age - 30)
  const physique = -1.5 * Math.max(0, 22 - age) - 0.75 * Math.max(0, age - 32)
  const passing = 0.5 * (Math.min(32, Math.max(22, age)) - 22)
  return [pace, 0, passing, dribbling, 0, physique]
}

/**
 * His card in the season starting `year` at `overall`, if we have one: his table card moved by the
 * difference in overall and by the years between.
 */
export function cardOf(name: string, year: number, overall: number, keeper: boolean): Card | undefined {
  const e = CARDS[name]
  if (!e) return undefined
  const [born, refYear, refOverall, ...card] = e
  const now = ageShift(year - born, keeper)
  const then = ageShift(refYear - born, keeper)
  // 30 is the lowest a card shows (a 1 out of 20).
  return card.map((v, i) => Math.round(Math.max(30, Math.min(99, v + overall - refOverall + now[i] - then[i])))) as Card
}
